#!/usr/bin/env node
// scripts/build-kb-snapshot.mjs
// Builds api/_lib/kb-snapshot.js: every knowledge chunk with its e5 embedding, bundled into the chat
// function so a cold start needs no Firestore read (the old path read all chunks every 5 minutes per
// instance, ~5 s on a cold start). Uses the same chunker and embedding model as build-kb.mjs, needs no
// credentials and makes no network calls once the model is cached locally.
//
// Run after editing knowledge/*:  node scripts/build-kb-snapshot.mjs   (npm run build:kb also uploads to Firestore)

import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { chunkMarkdown, chunkPortfolio, splitByLanguage } from './lib/chunker.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'api', '_lib', 'kb-snapshot.js');
export const KB_FILES = ['company.md', 'services.md', 'services-detailed.md', 'nfc.md', 'events.md', 'faq.md', 'process.md', 'sales-playbook.md'];

export async function loadKnowledgeChunks(root = ROOT) {
  const all = [];
  for (const file of KB_FILES) {
    const byLang = splitByLanguage(await fs.readFile(path.join(root, 'knowledge', file), 'utf8'));
    for (const lang of ['en', 'ar', 'zh', 'ru']) {
      if (!byLang[lang]?.trim()) continue;
      all.push(...chunkMarkdown(byLang[lang], { source: file, lang, baseId: file.replace('.md', '') }));
    }
  }
  all.push(...chunkPortfolio(JSON.parse(await fs.readFile(path.join(root, 'knowledge', 'portfolio.json'), 'utf8'))));
  return all;
}

// Hash of what the chunks say (ids + text), so a test can tell when the snapshot is stale.
export function hashChunks(chunks) {
  const h = crypto.createHash('sha256');
  for (const c of chunks) h.update(`${c.id}\u0000${c.source}\u0000${c.lang}\u0000${c.heading}\u0000${c.text}\u0001`);
  return h.digest('hex').slice(0, 16);
}

async function main() {
  const { embedPassage, EMBED_MODEL_NAME, EMBED_DIM } = await import('./lib/embed.mjs');
  const chunks = await loadKnowledgeChunks();
  const rows = [];
  for (let i = 0; i < chunks.length; i += 1) {
    const c = chunks[i];
    if (process.stdout.isTTY) process.stdout.write(`\r[snapshot] ${i + 1}/${chunks.length} ${c.id.padEnd(40)}`);
    const vec = Float32Array.from(await embedPassage(c.text));
    rows.push([c.id, c.source, c.lang, c.heading, c.text, Buffer.from(vec.buffer).toString('base64')]);
  }
  const meta = { model: EMBED_MODEL_NAME, dim: EMBED_DIM, count: rows.length, hash: hashChunks(chunks), builtAt: new Date().toISOString() };
  const body = `// GENERATED by scripts/build-kb-snapshot.mjs. Do not edit by hand.\n// Rows: [id, source, lang, heading, text, base64 Float32 embedding].\nexport const KB_META = ${JSON.stringify(meta)};\nexport const KB_ROWS = ${JSON.stringify(rows)};\n`;
  await fs.writeFile(OUT, body);
  console.log(`\n[snapshot] wrote ${path.relative(ROOT, OUT)}: ${rows.length} chunks, ${(body.length / 1024).toFixed(0)} KB, hash ${meta.hash}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
